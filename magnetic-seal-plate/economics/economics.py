"""Экономическая оценка проекта МВГП. Все цены — оценки на 2026 г., руб. без НДС."""
import math

# ---------------------------------------------------------------- 1. себестоимость комплекта
BOM = [
    ("Магнитные блоки переключаемые ×4", "на базе захвата 100 кг, полюса под радиус", 4 * 7000),
    ("Корпус-пластина", "АМг6, гибка, фрезеровка окон и канавок", 12000),
    ("Уплотнители NBR", "два контура и манжета конуса", 3000),
    ("Полый конус и нажимной винт", "латунь ЛС59, бобышка", 4500),
    ("Кран и шланг отвода", "шаровой кран 1/2\", шланг МБС 3 м", 3500),
    ("Мановакуумметр и штуцеры", "с обратным клапаном", 2500),
    ("Ручной вакуумный насос", "", 3500),
    ("Стяжные ремни ×2", "режим Б", 6000),
    ("Кейс и ЗИП", "сменные конусы и прокладки", 6000),
    ("Сборка и испытание", "опрессовка, паспорт", 8000),
]
direct = sum(c for *_, c in BOM)
overhead = 0.20
cost = direct * (1 + overhead)
markup = 0.40
price = round(cost * (1 + markup), -3)

# ---------------------------------------------------------------- 2. эффект для заказчика
RHO, MU = 850.0, 0.62
USD = 85.0
BBL_PER_T = 7.3
def oil_rub_t(usd_bbl):
    return usd_bbl * BBL_PER_T * USD

def leak_t_h(d_mm, dp_mpa):
    A = math.pi * (d_mm / 1000) ** 2 / 4
    v = math.sqrt(2 * dp_mpa * 1e6 / RHO)
    return MU * A * v * 3600 * RHO / 1000      # т/ч

def tank_dp(h_m):
    return RHO * 9.81 * h_m / 1e6

cases = [
    ("Свищ Ø5 мм, нефтепровод, 2,5 МПа", 5, 2.5),
    ("Свищ Ø10 мм, нефтепровод, 2,5 МПа", 10, 2.5),
    ("Отверстие Ø20 мм, РВС, напор 15 м", 20, tank_dp(15)),
]
SAVED_H = 1.0        # насколько раньше МВГП останавливает течь, ч
P_BASE, P_NOW = 60, 92   # $/барр: бюджет РФ 2026 и средняя Urals за сентябрь 2026

# ---------------------------------------------------------------- 3. проект и окупаемость
RND = [
    ("Моделирование магнитной системы и расчёты", 300_000),
    ("3D-модель, КД, типоразмерный ряд", 250_000),
    ("Три прототипа", 450_000),
    ("Испытательный стенд до 10 МПа", 600_000),
    ("Испытания: отрыв, сдвиг, герметичность, −50 °C", 300_000),
    ("Патентование", 150_000),
    ("Оснастка для серии", 400_000),
    ("Декларирование и опытная эксплуатация", 250_000),
]
rnd = sum(c for _, c in RND)
rnd_total = rnd * 1.10                 # +10 % непредвиденные
SALES = [40, 80, 120, 120, 120]        # комплектов в год
FIXED = 500_000                        # продвижение, гарантия, руб/год
RATE = 0.18                            # ставка дисконтирования
TAX = 0.25                             # налог на прибыль с 2025 г.

if __name__ == "__main__":
    print("== 1. Себестоимость")
    for n, note, c in BOM:
        print(f"  {n:38s} {c:>8,.0f}")
    print(f"  прямые затраты {direct:,.0f}; с накладными 20% {cost:,.0f}; цена (+40%) {price:,.0f}")
    margin = price - cost
    print(f"  маржа на комплект {margin:,.0f}")

    print("== 2. Эффект для заказчика")
    for p in (P_BASE, P_NOW):
        print(f"  нефть ${p}/барр = {oil_rub_t(p):,.0f} руб/т")
    for name, dmm, dp in cases:
        q = leak_t_h(dmm, dp)
        print(f"  {name}: {q:.1f} т/ч; за {SAVED_H} ч — {q*SAVED_H*oil_rub_t(P_BASE)/1e3:,.0f} тыс. руб (при $60), "
              f"{q*SAVED_H*oil_rub_t(P_NOW)/1e3:,.0f} тыс. (при $92); комплектов окупает: {q*SAVED_H*oil_rub_t(P_BASE)/price:.1f}")

    print("== 3. Проект")
    print(f"  НИОКР {rnd:,.0f}; с резервом {rnd_total:,.0f}")
    cf = [-rnd_total] + [(n * margin - FIXED) * (1 - TAX) for n in SALES]
    cum, dcum, npv, pb, dpb = 0, 0, 0, None, None
    for t, c in enumerate(cf):
        dc = c / (1 + RATE) ** t
        prev, dprev = cum, dcum
        cum += c; dcum += dc; npv += dc
        if pb is None and cum >= 0 and t > 0: pb = t - 1 + (-prev) / c
        if dpb is None and dcum >= 0 and t > 0: dpb = t - 1 + (-dprev) / dc
        print(f"  год {t}: поток {c/1e6:6.2f} млн, накопл. {cum/1e6:6.2f}, дисконт. накопл. {dcum/1e6:6.2f}")
    lo, hi = 0.0, 5.0
    for _ in range(100):
        mid = (lo + hi) / 2
        v = sum(c / (1 + mid) ** t for t, c in enumerate(cf))
        lo, hi = (mid, hi) if v > 0 else (lo, mid)
    print(f"  NPV {npv/1e6:.2f} млн; срок окупаемости {pb:.1f} г.; дисконт. {dpb:.1f} г.; IRR {lo*100:.0f} %")
    print(f"  точка безубыточности по НИОКР: {rnd_total/margin:.0f} комплектов")
