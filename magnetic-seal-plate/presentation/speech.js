function table(rows, widths, headerTexts) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, w, opts = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    borders,
    shading: opts.fill ? { type: ShadingType.CLEAR, color: "auto", fill: opts.fill } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: [new TextRun({ text, bold: !!opts.bold, color: opts.color, size: 22 })] })],
  });
  const trs = [];
  if (headerTexts) trs.push(new TableRow({ tableHeader: true,
    children: headerTexts.map((t, i) => cell(t, widths[i], { bold: true, color: "FFFFFF", fill: NAVY })) }));
  rows.forEach((r, ri) => {
    const last = ri === rows.length - 1 && r[0] === "Всего";
    trs.push(new TableRow({ children: r.map((t, i) => cell(t, widths[i], last ? { bold: true, fill: "DCE9F5" } : {})) }));
  });
  return new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: widths, rows: trs });
}

